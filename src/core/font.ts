export const GLYPH_W = 5;
export const GLYPH_H = 8;
export const CHAR_ADVANCE = 6;
export const LINE_HEIGHT = 10;

type Bitmap = { rows: number[]; w: number };
const cache = new Map<string, Bitmap>();

function bitmap(ch: string): Bitmap {
  let bm = cache.get(ch);
  if (bm) return bm;
  const src = GLYPHS[ch] ?? GLYPHS['?'];
  const rows = src.split('/').map((r) => {
    let mask = 0;
    for (let i = 0; i < GLYPH_W; i++) if (r[i] === '#') mask |= 1 << i;
    return mask;
  });
  bm = { rows, w: GLYPH_W };
  cache.set(ch, bm);
  return bm;
}

/** Stable per-glyph wobble so lettering looks written rather than typeset. */
function wobble(ch: string, index: number): number {
  const h = (ch.charCodeAt(0) * 2654435761 + index * 40503) >>> 0;
  return (h % 3) - 1;
}

export type TextOpts = {
  colour: string;
  /** Vertical wobble in pixels, 0 for typeset. Doc 17.5. */
  jitter?: boolean;
  /** Extra pixels between glyphs. */
  tracking?: number;
  /** One-pixel drop shadow in this colour, drawn under the glyph. */
  shadow?: string;
  /** 'left' | 'center' | 'right' */
  align?: 'left' | 'center' | 'right';
  /** Scale in whole pixels. 2 doubles every pixel of the glyph. */
  scale?: number;
};

export function textWidth(str: string, opts: TextOpts = { colour: '' }): number {
  const tracking = opts.tracking ?? 0;
  const scale = opts.scale ?? 1;
  return Math.max(0, str.length * (CHAR_ADVANCE + tracking) - tracking) * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  opts: TextOpts,
): void {
  const tracking = opts.tracking ?? 0;
  const scale = opts.scale ?? 1;
  const w = textWidth(str, opts);
  let px = Math.round(x);
  if (opts.align === 'center') px = Math.round(x - w / 2);
  else if (opts.align === 'right') px = Math.round(x - w);
  const baseY = Math.round(y);

  for (let pass = opts.shadow ? 0 : 1; pass < 2; pass++) {
    ctx.fillStyle = pass === 0 ? opts.shadow! : opts.colour;
    const ox = pass === 0 ? 1 : 0;
    const oy = pass === 0 ? 1 : 0;
    let cx = px;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      const bm = bitmap(ch);
      const jy = opts.jitter ? wobble(ch, i) : 0;
      for (let r = 0; r < bm.rows.length; r++) {
        const mask = bm.rows[r];
        if (!mask) continue;
        for (let c = 0; c < GLYPH_W; c++) {
          if (mask & (1 << c)) {
            ctx.fillRect(
              cx + (c + ox) * scale,
              baseY + (r + oy) * scale + jy,
              scale,
              scale,
            );
          }
        }
      }
      cx += (CHAR_ADVANCE + tracking) * scale;
    }
  }
}

/** Greedy word wrap at a pixel width. Returns lines. */
export function wrapText(str: string, maxPx: number, opts: TextOpts = { colour: '' }): string[] {
  const words = str.split(' ');
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (textWidth(candidate, opts) <= maxPx || !line) line = candidate;
    else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}
